"""Compact, score-first workspace for mouse and EOP-style keyboard entry."""
from PySide6.QtCore import QMargins, Qt
from PySide6.QtGui import QFont
from PySide6.QtPdf import QPdfDocument
from PySide6.QtPdfWidgets import QPdfView
from PySide6.QtWidgets import (
    QCheckBox,
    QComboBox,
    QHBoxLayout,
    QLabel,
    QLineEdit,
    QMenu,
    QPlainTextEdit,
    QProgressBar,
    QPushButton,
    QScrollArea,
    QSizePolicy,
    QSpinBox,
    QSplitter,
    QStackedWidget,
    QTabWidget,
    QToolButton,
    QVBoxLayout,
    QWidget,
)

from .model import DURATIONS, KEYS, METERS
from .score_view import NoteList


def build_workspace(self, label, button):
    central = QWidget()
    self.setCentralWidget(central)
    root = QVBoxLayout(central)
    root.setContentsMargins(12, 8, 12, 8)
    root.setSpacing(8)
    header = QHBoxLayout()
    header.addWidget(label("簡譜工房", "brand"))
    header.addSpacing(12)
    for text, fn in (("新建", self.new_project), ("開啟", self.open_file), ("照片辨識", self.import_photo)):
        header.addWidget(button(text, fn))
    self.undo_button = button("↶ 復原", self.undo)
    self.redo_button = button("↷ 重做", self.redo)
    header.addWidget(self.undo_button)
    header.addWidget(self.redo_button)
    header.addStretch()
    self.save_button = button("儲存", self.save)
    header.addWidget(self.save_button)
    self.export_button = QPushButton("匯出 / 列印")
    self.export_button.setObjectName("primary")
    menu = QMenu(self)
    for text, kind in (("PDF 樂譜…", "pdf"), ("MIDI 音樂…", "midi"), ("簡譜文字 .jly…", "jly"), ("LilyPond…", "ly"), ("辨識結果 MusicXML…", "musicxml")):
        menu.addAction(text, lambda k=kind: self.export(k))
    menu.addSeparator()
    menu.addAction("列印預覽…", self.show_print_preview)
    menu.addAction("開啟 PDF / 列印", self.open_pdf)
    self.export_button.setMenu(menu)
    header.addWidget(self.export_button)
    root.addLayout(header)

    views = QHBoxLayout()
    views.addWidget(label("畫面"))
    self.workspace_view = QComboBox()
    for text, value in (("編輯樂譜", "score"), ("原圖對照", "photo")):
        self.workspace_view.addItem(text, value)
    views.addWidget(self.workspace_view)
    self.metadata_button = button("樂曲設定", lambda checked: self.score_settings.setVisible(checked))
    self.metadata_button.setCheckable(True)
    views.addWidget(self.metadata_button)
    self.mode_button = button("進階語法", self.switch_mode)
    views.addWidget(self.mode_button)
    views.addWidget(label("直接在同一張譜閱讀與編輯；列印與 PDF 請用「匯出 / 列印」。", "muted", True), 1)
    self.play_button = button("▶ 試聽", self.play_midi)
    self.play_button.setToolTip("Enter 試聽 / 停止（音符區內）")
    views.addWidget(self.play_button)
    views.addWidget(button("快捷鍵", self.show_help))
    root.addLayout(views)

    self.split = QSplitter(Qt.Orientation.Horizontal)
    self.split.setChildrenCollapsible(False)
    self.editor = QWidget()
    edit = QVBoxLayout(self.editor)
    edit.setContentsMargins(0, 0, 8, 0)
    edit.setSpacing(6)
    self.score_settings = QWidget()
    metadata = QVBoxLayout(self.score_settings)
    metadata.setContentsMargins(0, 0, 0, 0)
    metadata.setSpacing(6)
    edit.addWidget(self.score_settings)
    self.score_settings.hide()
    row = QHBoxLayout()
    self.title_field = QLineEdit()
    self.title_field.setAccessibleName("曲名")
    self.title_field.setPlaceholderText("曲名")
    self.title_field.setMinimumWidth(40)
    self.composer_field = QLineEdit()
    self.composer_field.setPlaceholderText("作曲者 / 來源")
    self.composer_field.setMinimumWidth(40)
    row.addWidget(self.title_field, 3)
    row.addWidget(self.composer_field, 2)
    metadata.addLayout(row)
    row = QHBoxLayout()
    self.key_field = QComboBox()
    self.key_field.addItems(KEYS)
    self.meter_field = QComboBox()
    self.meter_field.addItems(METERS)
    self.tempo_field = QSpinBox()
    self.tempo_field.setRange(20, 300)
    self.tempo_field.setSuffix(" BPM")
    for text, widget in (("1 =", self.key_field), ("拍號", self.meter_field), ("速度", self.tempo_field)):
        row.addWidget(label(text))
        row.addWidget(widget)
    row.addStretch()
    row.addWidget(button("紙張與排版", self.layout_settings))
    metadata.addLayout(row)
    self.title_field.editingFinished.connect(self.capture_fields)
    self.composer_field.editingFinished.connect(self.capture_fields)
    self.key_field.currentTextChanged.connect(self.capture_fields)
    self.meter_field.currentTextChanged.connect(self.capture_fields)
    self.tempo_field.valueChanged.connect(self.capture_fields)

    self.editor_stack = QStackedWidget()
    visual = QWidget()
    vis = QVBoxLayout(visual)
    vis.setContentsMargins(0, 0, 0, 0)
    vis.setSpacing(6)
    row = QHBoxLayout()
    self.input_mode = QComboBox()
    self.input_mode.addItem("新增音符", "insert")
    self.input_mode.addItem("修改音符", "edit")
    self.input_mode.addItem("填寫小節", "fill")
    self.input_mode.setToolTip("空白鍵切換新增 / 修改（音符區內，沿用 EOP 習慣）")
    self.input_mode.currentIndexChanged.connect(self.update_selection)
    row.addWidget(self.input_mode)
    self.insert_position = QComboBox()
    for text, value in (("插在選取後", "after"), ("插在選取前", "before"), ("加到曲尾", "end")):
        self.insert_position.addItem(text, value)
    self.insert_position.currentIndexChanged.connect(self.update_selection)
    row.addWidget(self.insert_position)
    row.addStretch()
    row.addWidget(label("小節"))
    self.bar_jump = QSpinBox()
    self.bar_jump.setRange(1, 10000)
    self.bar_jump.setMaximumWidth(75)
    self.bar_jump.editingFinished.connect(self.jump_bar)
    row.addWidget(self.bar_jump)
    self.score_zoom = QComboBox()
    for zoom in (75, 100, 125, 150, 200):
        self.score_zoom.addItem(f"{zoom}%", zoom)
    self.score_zoom.setCurrentIndex(1)
    row.addWidget(self.score_zoom)
    vis.addLayout(row)
    row = QHBoxLayout()
    self.add_bar_button = QToolButton()
    self.add_bar_button.setText("＋新增小節")
    self.add_bar_button.setPopupMode(QToolButton.ToolButtonPopupMode.MenuButtonPopup)
    self.add_bar_button.setToolTip("在所選小節後新增一小節；箭頭可選前插、曲尾或多個小節。")
    self.add_bar_button.clicked.connect(lambda: self.insert_bars("after"))
    self.bar_menu = QMenu(self)
    self.bar_menu.aboutToShow.connect(lambda: (self.bar_menu.clear(), self.add_measure_menu(self.bar_menu)))
    self.add_bar_button.setMenu(self.bar_menu)
    row.addWidget(self.add_bar_button)
    self.measure_controls = [self.add_bar_button]
    for text, command, hint in (("重複小節", "duplicate", "複製所選連續小節，插在原段之後"),
                                ("清空小節", "clear", "保留小節與拍數，改成休止符"),
                                ("刪除小節", "delete", "移除整小節，後面的音樂向前移")):
        control = button(text, lambda _, a=command: self.measure_action(a))
        control.setToolTip(hint)
        row.addWidget(control)
        self.measure_controls.append(control)
    row.addStretch()
    vis.addLayout(row)
    self.measure_selection = label("點小節號選取整小節", "muted", True)
    self.measure_notice = label("", "notice", True)
    self.measure_notice.hide()
    vis.addWidget(self.measure_notice)
    row = QHBoxLayout()
    self.pitch_buttons = []
    for degree in (1, 2, 3, 4, 5, 6, 7, 0):
        b = button(str(degree), lambda _, d=degree: self.input_pitch(d), "pitch")
        b.setToolTip(f"數字鍵 {degree} · {'休止符' if degree == 0 else '音符'}")
        self.pitch_buttons.append(b)
        row.addWidget(b)
    vis.addLayout(row)

    self.notes = NoteList()
    self.notes.pitch.connect(self.input_pitch)
    self.notes.delete.connect(self.delete_note)
    self.notes.currentRowChanged.connect(self.select_note)
    self.notes.selectionEdited.connect(self.update_selection)
    self.notes.command.connect(self.note_command)
    self.notes.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)
    self.notes.customContextMenuRequested.connect(self.note_menu)
    self.score_zoom.currentIndexChanged.connect(lambda: self.notes.set_zoom(self.score_zoom.currentData()))
    self.selection_label = label("", "selection", True)
    row = QHBoxLayout()
    self.degree = QComboBox()
    for value in range(8):
        self.degree.addItem("休止 0" if value == 0 else f"音高 {value}", value)
    self.degree.setCurrentIndex(1)
    self.duration = QComboBox()
    for value, text in DURATIONS.items():
        self.duration.addItem(text, value)
    self.duration.setCurrentIndex(2)
    self.octave = QComboBox()
    for value, text in ((-2, "低兩八度"), (-1, "低八度"), (0, "中音"), (1, "高八度"), (2, "高兩八度")):
        self.octave.addItem(text, value)
    self.octave.setCurrentIndex(2)
    self.accidental = QComboBox()
    for text, value in (("無升降", ""), ("升 ♯", "#"), ("降 ♭", "b")):
        self.accidental.addItem(text, value)
    self.dotted = QCheckBox("附點")
    for field, widget in (("degree", self.degree), ("duration", self.duration), ("octave", self.octave), ("accidental", self.accidental)):
        widget.setMinimumWidth(60)
        widget.setSizePolicy(QSizePolicy.Policy.Ignored, QSizePolicy.Policy.Fixed)
        widget.setPlaceholderText("不同")
        widget.currentIndexChanged.connect(lambda _, f=field, w=widget: self.edit_property(f, w.currentData()))
        row.addWidget(widget)
    self.dotted.checkStateChanged.connect(lambda state: self.edit_property("dotted", state == Qt.CheckState.Checked) if state != Qt.CheckState.PartiallyChecked else None)
    row.addWidget(self.dotted)
    vis.addLayout(row)
    row = QHBoxLayout()
    self.selection_buttons = []
    for text, command in (("剪下", "cut"), ("複製", "copy"), ("貼上", "paste"), ("重複", "duplicate"), ("刪除", "delete")):
        b = button(text, lambda _, c=command: self.note_command(c))
        row.addWidget(b)
        if command != "paste":
            self.selection_buttons.append(b)
    row.addStretch()
    row.addWidget(button("二胡 / 記號", self.notation_settings))
    vis.addLayout(row)
    vis.addWidget(self.notes, 1)
    row = QHBoxLayout()
    self.rhythm_label = label("", "muted", True)
    row.addWidget(self.rhythm_label, 1)
    self.problem_button = button("定位問題", self.goto_problem)
    row.addWidget(self.problem_button)
    row.addWidget(button("補齊休止符", self.fill_bar))
    vis.addLayout(row)
    self.lyrics = QLineEdit()
    self.lyrics.setPlaceholderText("歌詞（選填）· 二胡純器樂可留白")
    self.lyrics.editingFinished.connect(self.capture_fields)
    self.staff = QCheckBox("五線譜對照")
    self.staff.toggled.connect(self.capture_fields)
    row = QHBoxLayout()
    row.addWidget(self.lyrics, 1)
    row.addWidget(self.staff)
    vis.addLayout(row)
    self.editor_stack.addWidget(visual)
    advanced = QWidget()
    advanced_layout = QVBoxLayout(advanced)
    advanced_layout.setContentsMargins(0, 0, 0, 0)
    advanced_layout.addWidget(label("進階 jianpu-ly：支援弱起、三連音、倚音、多聲部等。返回時保留視覺草稿。", "notice", True))
    advanced_layout.addWidget(button("插入常用語法…", self.source_snippets))
    self.source = QPlainTextEdit()
    self.source.setUndoRedoEnabled(False)
    self.source.installEventFilter(self)
    self.source.setContextMenuPolicy(Qt.ContextMenuPolicy.CustomContextMenu)
    self.source.customContextMenuRequested.connect(self.source_menu)
    self.source.setFont(QFont("Consolas", 12))
    self.source.setAccessibleName("簡譜原始碼")
    self.source.textChanged.connect(self.source_changed)
    advanced_layout.addWidget(self.source, 1)
    self.editor_stack.addWidget(advanced)
    edit.addWidget(self.editor_stack, 1)
    self.editor_container = QScrollArea()
    self.editor_container.setFrameShape(QScrollArea.Shape.NoFrame)
    self.editor_container.setWidgetResizable(True)
    self.editor_container.setWidget(self.editor)
    self.editor_container.setMinimumWidth(390)
    self.split.addWidget(self.editor_container)

    self.preview_panel = QWidget()
    self.preview_panel.setMinimumWidth(275)
    pv = QVBoxLayout(self.preview_panel)
    pv.setContentsMargins(8, 0, 0, 0)
    pv.setSpacing(6)
    row = QHBoxLayout()
    self.preview_heading = label("列印預覽", "section")
    row.addWidget(self.preview_heading)
    row.addStretch()
    self.auto_check = QCheckBox("自動")
    self.auto_check.setChecked(True)
    self.auto_check.toggled.connect(self.toggle_auto)
    row.addWidget(self.auto_check)
    self.preview_button = button("更新", lambda: self.render_score(True), "primary")
    row.addWidget(self.preview_button)
    row.addWidget(button("返回樂譜", lambda: self.change_workspace(0)))
    pv.addLayout(row)
    self.preview_status = label("需要列印或匯出 PDF 時才排版。", "muted", True)
    pv.addWidget(self.preview_status)
    self.preview_tabs = QTabWidget()
    self.preview_tabs.tabBar().hide()
    pdf_page = QWidget()
    pdf_layout = QVBoxLayout(pdf_page)
    pdf_layout.setContentsMargins(4, 6, 4, 0)
    row = QHBoxLayout()
    for text, fn in (("−", lambda: self.zoom(.8)), ("符合寬度", self.fit_pdf), ("＋", lambda: self.zoom(1.25))):
        row.addWidget(button(text, fn))
    row.addStretch()
    row.addWidget(button("紙張設定", self.layout_settings))
    row.addWidget(button("匯出 PDF", lambda: self.export("pdf")))
    row.addWidget(button("開啟列印", self.open_pdf))
    pdf_layout.addLayout(row)
    self.pdf_document = QPdfDocument(self)
    self.pdf_view = QPdfView()
    self.pdf_view.setDocument(self.pdf_document)
    self.pdf_view.setPageMode(QPdfView.PageMode.MultiPage)
    self.pdf_view.setZoomMode(QPdfView.ZoomMode.FitToWidth)
    self.pdf_view.setDocumentMargins(QMargins(10, 10, 10, 10))
    pdf_layout.addWidget(self.pdf_view, 1)
    self.preview_tabs.addTab(pdf_page, "PDF")
    photo_page = QWidget()
    photo_layout = QVBoxLayout(photo_page)
    photo_layout.setContentsMargins(4, 6, 4, 0)
    row = QHBoxLayout()
    for text, fn in (("−", lambda: self.zoom_photo(.8)), ("符合寬度", lambda: self.zoom_photo(0)), ("＋", lambda: self.zoom_photo(1.25))):
        row.addWidget(button(text, fn))
    photo_layout.addLayout(row)
    self.photo_label = QLabel("匯入照片後，在此放大對照原圖。")
    self.photo_label.setAlignment(Qt.AlignmentFlag.AlignCenter)
    self.photo_scroll = QScrollArea()
    self.photo_scroll.setWidgetResizable(False)
    self.photo_scroll.setWidget(self.photo_label)
    photo_layout.addWidget(self.photo_scroll, 1)
    self.preview_tabs.addTab(photo_page, "原圖校對")
    log_page = QWidget()
    log_layout = QVBoxLayout(log_page)
    self.log = QPlainTextEdit()
    self.log.setReadOnly(True)
    log_layout.addWidget(self.log)
    log_layout.addWidget(button("複製完整紀錄", self.copy_log))
    self.preview_tabs.addTab(log_page, "作業訊息")
    pv.addWidget(self.preview_tabs, 1)
    self.split.addWidget(self.preview_panel)
    self.split.setSizes([830, 500])
    root.addWidget(self.split, 1)
    footer = QHBoxLayout()
    self.workspace_view.currentIndexChanged.connect(self.change_workspace)
    self.input_hint = label("0–7 輸入 · 空白切換模式 · Shift 多選 · Enter 試聽", "muted", True)
    self.input_hint.hide()
    footer.addWidget(self.selection_label, 1)
    footer.addWidget(self.measure_selection)
    root.addLayout(footer)
    self.progress = QProgressBar()
    self.progress.setRange(0, 0)
    self.progress.setTextVisible(False)
    self.progress.setMaximumHeight(3)
    self.progress.hide()
    root.addWidget(self.progress)
    self.cancel_button = button("取消作業", self.cancel_task)
    self.cancel_button.hide()
    self.statusBar().addPermanentWidget(self.cancel_button)
    self.statusBar().showMessage("就緒 · 離線編輯")
    self.change_workspace(0)
